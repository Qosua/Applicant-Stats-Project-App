DataBaseManager& DataBaseManager::instance() {
    static DataBaseManager inst;
    return inst;
}

bool DataBaseManager::init() {

    m_db = QSqlDatabase::addDatabase("QSQLITE");
    m_db.setDatabaseName(AppPathsManager::dbPath);

    if (!m_db.open()) {
        qCritical() << "SQL ERROR: cannot open database" << AppPathsManager::dbPath
                    << m_db.lastError().text();
        return false;
    }

    QSqlQuery("PRAGMA foreign_keys = ON;", m_db);

    if (!createDatabase())
        return false;
    return fillDefaultData();
}

QSqlDatabase& DataBaseManager::db() { return m_db; }

QList<QVariantList> DataBaseManager::getEntryCommisionsList() const {

    if (!m_db.isOpen()) {
        qCritical() << "SQL ERROR" << "DatabaseManager could not open connection to database";
        return {};
    }

    QSqlQuery query(m_db);
    if (!query.exec(getQueryText("get-entry_commisions-list.sql"))) {
        qCritical() << "SQL ERROR" << query.lastError().text();
        return {};
    }

    QList<QVariantList> list;
    while (query.next()) {
        list << QVariantList{query.value("uni_name").toString(),
                             query.value("is_bachelor").toBool(),
                             query.value("year").toInt()};
    }

    return list;
}

int DataBaseManager::getEntryCommissionsIndexForTable(const QString& tableName) const {

    if (!m_db.isOpen()) {
        qCritical() << "SQL ERROR" << "DatabaseManager could not open connection to database";
        return -1;
    }

    QSqlQuery query(m_db);
    if (!query.prepare(getQueryText("get-table_preset_current_id.sql"))) {
        qCritical() << "SQL ERROR" << query.lastError().text();
        return -1;
    }
    query.bindValue(":tName", tableName);

    if (!query.exec()) {
        qCritical() << "SQL ERROR" << query.lastError().text();
        return -1;
    }

    if (query.next())
        return query.value(0).toInt();

    return -1;
}

bool DataBaseManager::isTableExist(const QString& tableName) const {

    if (!m_db.isOpen()) {
        qCritical() << "SQL ERROR" << "DatabaseManager could not open connection to database";
        return false;
    }

    QSqlQuery query(m_db);
    query.prepare(getQueryText("is-table-exist.sql"));
    query.bindValue(":tableName", tableName);

    if (!query.exec()) {
        qCritical() << "SQL ERROR" << query.lastError().text();
        return false;
    }

    return query.next() && query.value(0).toInt() == 1;
}

QList<QString> DataBaseManager::getEntryCommisionColumnsNamesListFromDb(const QString& name,
                                                                         bool isBachelor,
                                                                         int year) const {

    if (!m_db.isOpen()) {
        qCritical() << "SQL ERROR" << "DatabaseManager could not open connection to database";
        return {};
    }

    QSqlQuery query(m_db);
    query.prepare(getQueryText("get-columns_names.sql"));
    query.bindValue(":name", name);
    query.bindValue(":isBachelor", isBachelor);
    query.bindValue(":year", year);

    if (!query.exec()) {
        qCritical() << "SQL ERROR" << query.lastError().text();
        return {};
    }

    QList<QString> strList;
    if (query.next())
        for (int i = 0; i < 15; ++i)
            strList.append(query.value(i).toString());

    return strList;
}

QSqlQuery* DataBaseManager::getKCP(const QString& name, const bool& isBachelor, int year) const {

    if (!m_db.isOpen()) {
        qCritical() << "SQL ERROR" << "DatabaseManager could not open connection to database";
        return nullptr;
    }

    auto* query = new QSqlQuery(m_db);
    query->prepare(getQueryText("get-kcp.sql"));
    query->bindValue(":name", name);
    query->bindValue(":isBachelor", isBachelor);
    query->bindValue(":year", year);

    if (!query->exec()) {
        qCritical() << "SQL ERROR" << query->lastError().text();
        delete query;
        return nullptr;
    }

    return query;
}

bool DataBaseManager::changeEntryCommissionsIndexForTable(const QString& tableName, int index) {

    if (!m_db.isOpen()) {
        qCritical() << "SQL ERROR" << "DatabaseManager could not open connection to database";
        return false;
    }

    QSqlQuery query(m_db);
    query.prepare(getQueryText("change-table_preset_current_id.sql"));
    query.bindValue(":tName", tableName);
    query.bindValue(":newID", index);

    if (!query.exec()) {
        qCritical() << "SQL ERROR" << query.lastError().text();
        return false;
    }

    return true;
}

void DataBaseManager::addNewTablePreset(const QString& tableName, int commisionIndex) {

    if (isTableExist(tableName)) {
        changeEntryCommissionsIndexForTable(tableName, commisionIndex);
        return;
    }

    if (!m_db.isOpen()) {
        qCritical() << "SQL ERROR" << "DatabaseManager could not open connection to database";
        return;
    }

    QSqlQuery query(m_db);
    query.prepare(getQueryText("insert-current_table_preset.sql"));
    query.bindValue(":tableName", tableName);
    query.bindValue(":entry_commision_id", commisionIndex);

    if (!query.exec())
        qCritical() << "SQL ERROR" << query.lastError().text();
}

bool DataBaseManager::createDatabase() {

    if (!m_db.isOpen()) {
        qCritical() << "SQL ERROR" << "DatabaseManager could not open connection to database";
        return false;
    }

    QSqlQuery query(m_db);

    const char* tables[] = {
        "create-columns_mapping-table.sql",
        "create-current_table_presets-table.sql",
        "create-entry_commisions-table.sql",
        "create-kcp-table.sql",
    };
    for (const char* file : tables) {
        if (!query.exec(getQueryText(file))) {
            qCritical() << "SQL ERROR - DATABASE CREATION FAILED" << file << query.lastError().text();
            return false;
        }
    }

    const char* indexes[] = {
        "create-kcp-indexes.sql",
        "create-columns_mapping-indexes.sql",
    };
    for (const char* file : indexes) {
        if (!query.exec(getQueryText(file))) {
            qCritical() << "SQL ERROR - INDEXES CREATION FAILED" << file << query.lastError().text();
            return false;
        }
    }

    return true;
}

QString DataBaseManager::getQueryText(const QString& fileName) {

    QFile file(QStringLiteral(":/src/database/sql-queries/") + fileName);
    if (!file.open(QIODevice::ReadOnly | QIODevice::Text)) {
        qCritical() << "Can not open sql query file:" << fileName << file.errorString();
        return QString();
    }

    return QString::fromUtf8(file.readAll());
}

